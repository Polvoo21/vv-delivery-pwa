export function LegalPage() {
  const document = getLegalDocument(window.location.pathname);
  const sections = documentSections[document.id] || documentSections.requisites;

  function returnToSite(event) {
    const referrer = window.document.referrer;
    const currentOrigin = window.location.origin;
    if (referrer && referrer.startsWith(currentOrigin) && window.history.length > 1) {
      event.preventDefault();
      window.history.back();
    }
  }

  useEffect(() => {
    window.scrollTo(0, 0);
    window.document.title = `${document.title} | ${RESTAURANT.name}`;
  }, [document.title]);

  return (
    <SitePublicShell className="site-legal-page">
      <section className="site-legal-hero">
        <a className="site-legal-back" href="/" onClick={returnToSite}>
          <ChevronLeft size={18} />
          Вернуться назад
        </a>
        <p>Документы</p>
        <h1>{document.title}</h1>
        <span>{document.lead}</span>
        <div>
          <b>
            <Clock size={16} />
            Редакция от {LEGAL_ENTITY.updatedAt}
          </b>
          <b>
            <MapPin size={16} />
            {RESTAURANT.shortAddress}
          </b>
        </div>
      </section>

      <div className="site-legal-layout">
        <aside className="site-legal-nav" aria-label="Юридические документы">
          <h2>Документы</h2>
          {legalDocuments.map((item) => (
            <a className={item.id === document.id ? "is-active" : ""} href={item.path} key={item.id}>
              <FileText size={16} />
              {item.shortTitle}
            </a>
          ))}
        </aside>

        <article className="site-legal-card">
          {sections.map((section) => (
            <section key={section.title}>
              <h2>{section.title}</h2>
              {section.content}
            </section>
          ))}
        </article>
      </div>

      <SiteFooter />
    </SitePublicShell>
  );
}
